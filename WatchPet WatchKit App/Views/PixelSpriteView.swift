    // MARK: - Canvas rendering
    @ViewBuilder
    private func spriteCanvas(frame: Int) -> some View {
        if let image = UIImage(named: "\(spritePrefix)_\(frame)") {
            Image(uiImage: image)
                .interpolation(.none)
                .resizable()
                .frame(width: CGFloat(image.size.width) * pixelSize,
                       height: CGFloat(image.size.height) * pixelSize)
        } else if let def = Self.registry[spritePrefix] {
            let grid = def.frames[frame % def.frames.count]
            pixelCanvas(grid: grid, palette: def.palette)
        } else {
            let grid = Self.fallbackFrames[frame % Self.fallbackFrames.count]
            pixelCanvas(grid: grid, palette: Self.fallbackPalette)
        }
    }

    private func pixelCanvas(grid: [[Int]], palette: [Int: Color]) -> some View {
        let cols = grid[0].count
        let rows = grid.count
        return Canvas { ctx, _ in
            for row in 0..<rows {
                for col in 0..<grid[row].count {
                    let idx = grid[row][col]
                    guard idx != 0, let color = palette[idx] else { continue }
                    ctx.fill(
                        Path(CGRect(x: CGFloat(col) * pixelSize,
                                    y: CGFloat(row) * pixelSize,
                                    width: pixelSize, height: pixelSize)),
                        with: .color(color)
                    )
                }
            }
        }
        .frame(width: CGFloat(cols) * pixelSize, height: CGFloat(rows) * pixelSize)
    }

    // MARK: - Frame index
    private func currentFrame(for date: Date) -> Int {
        let interval = date.timeIntervalSinceReferenceDate
        return Int(interval * fps) % max(1, frameCount)
    }
